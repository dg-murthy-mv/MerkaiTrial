// COMPLETE FILE — 067. THE LINE TABLE GAINS A TAX CLASSIFICATION COLUMN,
// and on an Indian invoice that is not a nicety: a GST invoice has to
// carry the HSN or SAC code against every line. Products have carried the
// code since 051 and it stopped at the product — the line it ended up on
// had no field for it, so the document that legally needs it could not
// print it.
//
// The column appears ONLY when at least one printed line on the invoice
// has a code. Three of Merkai's four markets ask for nothing here, and a
// permanently empty column on a document a customer files with their
// accountant reads as something the sender forgot to fill in.
//
// 055. THE LINE TABLE HAD NO DISCOUNT COLUMN AT ALL.
//
// The totals block showed a "Discount:" line for the whole invoice, so the
// money added up — but a customer looking at a line could not see that it
// had been discounted, or by how much. The quote they accepted showed it
// per line; the invoice that followed did not. There is a Discount column
// now, printing the PERCENTAGE when the line was agreed as one, and the
// Description column gives up the width for it.
//
// 052b. Five changes, the last two found while here.
//
// 1. QUANTITY. Was line.Quantity.ToString(). Quantity is DECIMAL(18,4)
//    since 052, so that prints "3.0000" on a tax invoice. It is
//    QuantityDisplay now — "3", "12.5 m²", "3.5 days".
//
// 2. The Qty column was a CONSTANT 36pt, sized for "12". "12.5 m²" does
//    not fit. Widened to 64pt, taken from the Description column.
//
// 3. THE TAX COLUMN WAS ROUNDING THE RATE. "N0" on (TaxRate * 100)
// 071. A MILESTONE BANNER above the line-items table, printed ONLY on an
// invoice that bills one stage of a quote's payment schedule: "Milestone
// 2 of 3 — On delivery (40%)", with "Amounts shown are 40% of accepted
// quote QUO-0042" under it.
//
// It is not decoration. A milestone invoice's unit prices are a SHARE of
// the quote's, so a customer comparing "1 × 13,500" with a quoted 45,000
// has every reason to query it — and the answer has to be on the same
// page as the figures, not on a screen they cannot see. Every field is a
// snapshot taken when the invoice was raised; the schedule is never
// re-read for a document.
//
//    printed 12.5% as "13%" — on a TAX INVOICE, next to a tax amount
//    calculated from the real 12.5%, so the document contradicts itself
//    in front of whoever files it. "0.##" now, and formatted with the
//    tenant's culture like every other number here.
//
// 4. THE FOOTER SAID "Generated by LeadFlow CRM". On every invoice this
//    workspace has ever sent a customer. QuotePdfService already said
//    "Merkai CRM"; this one had been missed.
//
// 5. Payment amounts used "{p.Amount:N2}", which formats with whatever
//    culture the server thread has rather than the tenant's — so on an
//    INR invoice the totals grouped as 1,00,000.00 and the payment rows
//    beside them as 100,000.00. They use `culture` like everything else
//    now.
// =====================================================================

