using MerkaiTrial.Domain.Entities;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace MerkaiTrial.Infrastructure.Persistence.Configurations;

public class UserSessionConfiguration : IEntityTypeConfiguration<UserSession>
{
    public void Configure(EntityTypeBuilder<UserSession> b)
    {
        b.ToTable("UserSessions");
        b.HasKey(s => s.Id);

        // Not generated by SQL Server: the id goes into the cookie the
        // moment the row is made.
        b.Property(s => s.Id).ValueGeneratedNever();

        b.Property(s => s.EndReason).HasMaxLength(50);
        b.Property(s => s.IpAddress).HasMaxLength(64);
        b.Property(s => s.UserAgent).HasMaxLength(256);

        // "This person's sessions" — the clean-up at sign-in.
        b.HasIndex(s => new { s.UserId, s.ExpiresAtUtc })
         .HasDatabaseName("IX_UserSessions_UserId_ExpiresAtUtc");
    }
}
