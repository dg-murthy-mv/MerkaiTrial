-- =====================================================================
-- VERIFY
-- =====================================================================

SELECT
    s.[Name]                                                        AS Store,
    b.[Name]                                                        AS Branch,
    COUNT(t.[Id])                                                   AS TotalTables,
    SUM(t.[SeatingCapacity])                                        AS TotalSeats,
    SUM(CASE t.[Status] WHEN 'Available' THEN 1 ELSE 0 END)        AS Available,
    SUM(CASE t.[Status] WHEN 'Occupied'  THEN 1 ELSE 0 END)        AS Occupied,
    SUM(CASE t.[Status] WHEN 'Reserved'  THEN 1 ELSE 0 END)        AS Reserved
FROM      [dbo].[Table]  t
JOIN      [dbo].[Store]  s ON s.[Id] = t.[StoreId]
JOIN      [dbo].[Branch] b ON b.[Id] = t.[BranchId]
WHERE     t.[IsDeleted] = 0
GROUP BY  s.[Name], b.[Name]
ORDER BY  s.[Name], b.[Name];
GO
